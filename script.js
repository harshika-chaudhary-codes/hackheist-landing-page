```javascript
// Reveal sections and cards when they enter the screen.

const revealElements = document.querySelectorAll(
    ".about-grid, .about-banner, .section-heading, .event-card, .details-layout, .cta-container"
);

revealElements.forEach((element) => {
    element.classList.add("reveal");
});

if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver(
        (entries, observerInstance) => {
            entries.forEach((entry) => {
                if (entry.isIntersecting) {
                    entry.target.classList.add("visible");
                    observerInstance.unobserve(entry.target);
                }
            });
        },
        {
            threshold: 0.12
        }
    );

    revealElements.forEach((element) => {
        observer.observe(element);
    });
} else {
    revealElements.forEach((element) => {
        element.classList.add("visible");
    });
}


// Smooth scrolling for internal navigation links.

document.querySelectorAll('a[href^="#"]').forEach((link) => {
    link.addEventListener("click", (event) => {
        const targetId = link.getAttribute("href");

        if (!targetId || targetId === "#") {
            return;
        }

        const target = document.querySelector(targetId);

        if (target) {
            event.preventDefault();

            target.scrollIntoView({
                behavior: "smooth",
                block: "start"
            });
        }
    });
});


// Update the browser tab title if the page becomes hidden.

const originalTitle = document.title;

document.addEventListener("visibilitychange", () => {
    document.title = document.hidden
        ? "Come back to HackHeist!"
        : originalTitle;
});
```
